"""Render the looping binary rain frames used by the VPN home-screen widgets."""

from pathlib import Path
from random import Random

from PIL import Image, ImageDraw


WIDTH, HEIGHT = 336, 188
FRAME_COUNT = 36
FRAME_INTERVAL_MS = 60
DIGIT_STEP = 11
DIGITS = (
    ("01110", "11011", "10001", "10001", "10001", "11011", "01110"),
    ("00100", "01100", "00100", "00100", "00100", "00100", "01110"),
)


def main():
    resources = Path(__file__).resolve().parents[1] / "app/src/main/res"
    images = resources / "drawable-nodpi"
    images.mkdir(exist_ok=True)
    rng = Random(31)
    columns = []
    for column in range(22):
        x = 6 + column * 15 + rng.randrange(5)
        bits = [rng.randrange(2) for _ in range(rng.randrange(4, 9))]
        period = (len(bits) + rng.randrange(3, 7)) * DIGIT_STEP
        columns.append((x, bits, period, rng.randrange(period)))

    frames = []
    for frame in range(FRAME_COUNT):
        image = Image.new("RGBA", (WIDTH, HEIGHT))
        draw = ImageDraw.Draw(image)
        for x, bits, period, starting_position in columns:
            head = (starting_position + frame * period // FRAME_COUNT) % period
            for offset, digit in enumerate(bits):
                strength = 1 - offset / len(bits)
                color = (112, 167, 133, round(91 * strength**1.65))
                y = (head - offset * DIGIT_STEP) % period
                for start in range(y - period, HEIGHT, period):
                    for row, pixels in enumerate(DIGITS[digit]):
                        for col, pixel in enumerate(pixels):
                            if pixel == "1":
                                draw.point((x + col, start + row), fill=color)

        name = f"widget_rain_frame_{frame:02d}"
        image.save(images / f"{name}.png", optimize=True)
        frames.append(f'''    <ImageView
        style="@style/PhantomWidgetRainFrame"
        android:src="@drawable/{name}" />''')

    layout = resources / "layout/widget_rain_frames.xml"
    layout.write_text(f'''<!-- Generated by scripts/render_widget_rain.py. -->
<ViewFlipper xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/widget_rain_frames"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:autoStart="true"
    android:flipInterval="{FRAME_INTERVAL_MS}"
    android:measureAllChildren="false">

''' + "\n\n".join(frames) + "\n</ViewFlipper>\n", encoding="utf-8")


if __name__ == "__main__":
    main()
